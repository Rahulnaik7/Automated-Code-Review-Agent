"""Evaluates detection precision: naive LLM zero-shot baseline vs. the
full hybrid pipeline (Bandit + AST cross-validation + LangGraph-routed LLM
review), over the seeded-vulnerability benchmark.

    python -m eval.run_benchmark

Writes `outputs/benchmark_report.json` and prints a markdown summary table
(also saved to `outputs/benchmark_report.md`). The README's benchmark
numbers are generated by this script — rerun it after changing any
analysis/routing logic to keep the README's claims accurate.
"""
from __future__ import annotations

import json
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.diff_utils import only_python_files, parse_unified_diff  # noqa: E402
from src.graph.build_graph import build_review_graph  # noqa: E402
from src.graph.state import new_state  # noqa: E402
from src.llm.factory import build_llm_client  # noqa: E402

DATASET_PATH = ROOT / "data" / "benchmark" / "seeded_vulnerabilities.jsonl"
CONFIG_PATH = ROOT / "configs" / "agent.yaml"
OUT_DIR = ROOT / "outputs"


@dataclass
class ConfusionMatrix:
    tp: int = 0
    fp: int = 0
    fn: int = 0
    tn: int = 0
    false_positive_examples: List[str] = field(default_factory=list)
    false_negative_examples: List[str] = field(default_factory=list)

    def record(self, example_id: str, predicted: bool, actual: bool) -> None:
        if predicted and actual:
            self.tp += 1
        elif predicted and not actual:
            self.fp += 1
            self.false_positive_examples.append(example_id)
        elif not predicted and actual:
            self.fn += 1
            self.false_negative_examples.append(example_id)
        else:
            self.tn += 1

    @property
    def precision(self) -> float:
        denom = self.tp + self.fp
        return round(self.tp / denom, 4) if denom else 0.0

    @property
    def recall(self) -> float:
        denom = self.tp + self.fn
        return round(self.tp / denom, 4) if denom else 0.0

    @property
    def false_positive_rate(self) -> float:
        denom = self.fp + self.tn
        return round(self.fp / denom, 4) if denom else 0.0

    @property
    def accuracy(self) -> float:
        total = self.tp + self.fp + self.fn + self.tn
        return round((self.tp + self.tn) / total, 4) if total else 0.0

    def as_dict(self) -> Dict:
        return {
            "tp": self.tp, "fp": self.fp, "fn": self.fn, "tn": self.tn,
            "precision": self.precision, "recall": self.recall,
            "false_positive_rate": self.false_positive_rate,
            "accuracy": self.accuracy,
            "false_positive_examples": self.false_positive_examples,
            "false_negative_examples": self.false_negative_examples,
        }


def load_dataset() -> List[Dict]:
    examples = []
    with DATASET_PATH.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                examples.append(json.loads(line))
    return examples


def run_naive_baseline(examples: List[Dict], llm_client) -> ConfusionMatrix:
    cm = ConfusionMatrix()
    for ex in examples:
        file_diffs = only_python_files(parse_unified_diff(ex["diff_text"]))
        code = file_diffs[0].added_source() if file_diffs else ""
        results = llm_client.zero_shot_scan(file_path=ex["file"], code=code)
        predicted = any(r.is_issue for r in results)
        cm.record(ex["id"], predicted, ex["has_issue"])
    return cm


def run_hybrid_pipeline(examples: List[Dict], llm_client, config: Dict) -> ConfusionMatrix:
    app = build_review_graph(llm_client, config)
    cm = ConfusionMatrix()
    for ex in examples:
        state = new_state(ex["diff_text"])
        result = app.invoke(state)
        predicted = len(result.get("all_findings", [])) > 0
        cm.record(ex["id"], predicted, ex["has_issue"])
    return cm


def main() -> None:
    config = yaml.safe_load(CONFIG_PATH.read_text())
    llm_client = build_llm_client(config)
    examples = load_dataset()

    n_vuln = sum(1 for e in examples if e["has_issue"])
    print(f"Loaded {len(examples)} examples ({n_vuln} seeded issues, "
          f"{len(examples) - n_vuln} clean) from {DATASET_PATH.relative_to(ROOT)}\n")

    t0 = time.time()
    baseline_cm = run_naive_baseline(examples, llm_client)
    t1 = time.time()
    pipeline_cm = run_hybrid_pipeline(examples, llm_client, config)
    t2 = time.time()

    report = {
        "dataset": {
            "path": str(DATASET_PATH.relative_to(ROOT)),
            "size": len(examples),
            "seeded_issues": n_vuln,
            "clean": len(examples) - n_vuln,
        },
        "llm_provider": config.get("llm", {}).get("provider"),
        "baseline_naive_zero_shot": {**baseline_cm.as_dict(), "runtime_sec": round(t1 - t0, 2)},
        "hybrid_pipeline": {**pipeline_cm.as_dict(), "runtime_sec": round(t2 - t1, 2)},
        "precision_delta": round(pipeline_cm.precision - baseline_cm.precision, 4),
    }

    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / "benchmark_report.json").write_text(json.dumps(report, indent=2))

    md = _render_markdown(report)
    (OUT_DIR / "benchmark_report.md").write_text(md)

    print(md)
    print(f"\nWrote outputs/benchmark_report.json and outputs/benchmark_report.md")


def _render_markdown(report: Dict) -> str:
    b = report["baseline_naive_zero_shot"]
    p = report["hybrid_pipeline"]
    lines = [
        "# Benchmark Results",
        "",
        f"Dataset: {report['dataset']['size']} examples "
        f"({report['dataset']['seeded_issues']} seeded issues, "
        f"{report['dataset']['clean']} clean) · LLM provider: `{report['llm_provider']}`",
        "",
        "| Pipeline | Precision | Recall | False Positive Rate | Accuracy |",
        "| :--- | :---: | :---: | :---: | :---: |",
        f"| Naive LLM Zero-Shot | **{b['precision']}** | {b['recall']} | {b['false_positive_rate']} | {b['accuracy']} |",
        f"| Bandit + AST + LangGraph-routed LLM (Ours) | **{p['precision']}** | {p['recall']} | {p['false_positive_rate']} | {p['accuracy']} |",
        "",
        f"Precision delta: **{report['precision_delta']:+.4f}** "
        f"({'+' if report['precision_delta'] >= 0 else ''}{report['precision_delta'] * 100:.1f} pp)",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
